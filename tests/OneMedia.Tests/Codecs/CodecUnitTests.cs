    [Fact]
    public void AacExplicitAndBackwardCompatibleSbrSignalling()
    {
        // explicit: object type 5, core rate 24 kHz, stereo, extension rate 48 kHz, core type LC, GASpecificConfig
        byte[] explicitSbr = Bits((5, 5), (6, 4), (2, 4), (3, 4), (2, 5), (0, 3));
        Assert.True(AudioSpecificConfig.TryParse(explicitSbr, out AudioSpecificConfig a));
        Assert.True(a.SbrPresent);
        Assert.False(a.PsPresent);
        Assert.Equal(2, a.AudioObjectType);
        Assert.Equal(24000, a.SamplingFrequency);
        Assert.Equal(48000, a.OutputSamplingFrequency);
        Assert.Equal("mp4a.40.5", a.Rfc6381);
        Assert.Equal("HE-AAC", a.ProfileName);

        // explicit PS: object type 29, mono core
        byte[] ps = Bits((29, 5), (6, 4), (1, 4), (3, 4), (2, 5), (0, 3));
        Assert.True(AudioSpecificConfig.TryParse(ps, out AudioSpecificConfig p));
        Assert.True(p.PsPresent);
        Assert.Equal(2, p.Channels);
        Assert.Equal("mp4a.40.29", p.Rfc6381);

        // backward compatible: LC 24 kHz stereo, then sync extension 0x2b7, type 5, sbr flag, extension rate 48 kHz
        byte[] compat = Bits((2, 5), (6, 4), (2, 4), (0, 3), (0x2b7, 11), (5, 5), (1, 1), (3, 4));
        Assert.True(AudioSpecificConfig.TryParse(compat, out AudioSpecificConfig c));
        Assert.True(c.SbrPresent);
        Assert.False(c.ExplicitSignalling);
        Assert.Equal(48000, c.OutputSamplingFrequency);
        Assert.Equal(2, c.AudioObjectType);

        // plain LC 44.1 kHz stereo is 12 10
        Assert.True(AudioSpecificConfig.TryParse([0x12, 0x10], out AudioSpecificConfig lc));
        Assert.Equal(44100, lc.OutputSamplingFrequency);
        Assert.Equal(2, lc.Channels);
        Assert.Equal("mp4a.40.2", lc.Rfc6381);
    }

