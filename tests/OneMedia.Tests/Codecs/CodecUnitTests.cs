    private static byte[] Bits(params (int Value, int Count)[] fields)
    {
        List<byte> bytes = [];
        int current = 0, filled = 0;
        foreach ((int value, int count) in fields)
        {
            for (int i = count - 1; i >= 0; i--)
            {
                current = (current << 1) | ((value >> i) & 1);
                if (++filled == 8)
                {
                    bytes.Add((byte)current);
                    current = 0;
                    filled = 0;
                }
            }
        }

        if (filled > 0)
        {
            bytes.Add((byte)(current << (8 - filled)));
        }

        return [.. bytes];
    }

    // ---- allocation gates: header parsing and conversion into caller buffers allocate nothing per call ----

    private static readonly List<string> AllocationFailures = [];

    private static void AssertNoAllocation(string what, Action action)
    {
        for (int i = 0; i < 200; i++)
        {
            action();
        }

        long before = GC.GetAllocatedBytesForCurrentThread();
        for (int i = 0; i < 5000; i++)
        {
            action();
        }

        long delta = GC.GetAllocatedBytesForCurrentThread() - before;
        string? report = Environment.GetEnvironmentVariable("ONEMEDIA_CODEC_REPORT_DIR");
        if (report is not null)
        {
            File.AppendAllText(Path.Combine(report, "allocations.txt"), string.Create(CultureInfo.InvariantCulture, $"{what}: {delta} bytes over 5000 calls\n"));
        }

        if (delta != 0)
        {
            AllocationFailures.Add($"{what} allocated {delta} bytes over 5000 calls");
        }
    }

    [Fact]
    public void ParsingAllocatesNothing()
    {
        byte[] sample = new byte[200];
        byte[] annexB = [0, 0, 0, 1, .. H264Sps, 0, 0, 1, .. H264Pps, 0, 0, 1, 0x65, 1, 2, 3, 4, 5, 6, 7, 8];
        byte[] output = new byte[1024];
        byte[] lengthPrefixed = new byte[1024];
        Assert.Equal(OperationStatus.Done, NalRepackager.AnnexBToLengthPrefixed(annexB, 4, lengthPrefixed, out int lpLength));
        int dummy = 0;
        AssertNoAllocation("H.264 SPS", () => dummy += AvcSps.TryParse(H264Sps, out AvcSps s) ? s.Width : 0);
        AssertNoAllocation("HEVC SPS", () => dummy += HevcSps.TryParse(HevcSpsBytes, out HevcSps s) ? s.Width : 0);
        AssertNoAllocation("AV1 sequence header", () => dummy += SequenceHeader.TryFind(Av1Obus, out SequenceHeader s, out _) ? s.MaxFrameWidth : 0);
        AssertNoAllocation("AudioSpecificConfig", () => dummy += AudioSpecificConfig.TryParse(LcAsc, out AudioSpecificConfig s) ? s.Channels : 0);
        AssertNoAllocation("ADTS header", () => dummy += AdtsHeader.TryParse(Adts, out AdtsHeader s) ? s.FrameLength : 0);
        AssertNoAllocation("VP9 frame header", () => dummy += Vp9FrameHeader.TryParse(Vp9Frame, out Vp9FrameHeader s) ? s.Width : 0);
        AssertNoAllocation("MPEG-2 sequence header", () => dummy += Mpeg2SequenceHeader.TryFind(Mpeg2Head, out Mpeg2SequenceHeader s) ? s.Width : 0);
        AssertNoAllocation("AC-3 syncframe", () => dummy += Ac3SyncFrame.TryParse(Ac3Head, out Ac3SyncFrame s) ? s.FrameSize : 0);
        AssertNoAllocation("MPEG audio header", () => dummy += MpegAudioFrameHeader.TryParse(Mp3Head, out MpegAudioFrameHeader s) ? s.FrameLength : 0);
        AssertNoAllocation("Opus TOC", () => dummy += OpusToc.TryGetSamples(OpusPacket, out int s) ? s : 0);
        AssertNoAllocation("Annex B to length-prefixed", () => dummy += (int)NalRepackager.AnnexBToLengthPrefixed(annexB, 4, output, out _));
        AssertNoAllocation("length-prefixed to Annex B", () => dummy += (int)NalRepackager.LengthPrefixedToAnnexB(NalCodec.H264, lengthPrefixed.AsSpan(0, lpLength), 4, output, out _));
        Assert.True(dummy != 0);
        Assert.NotNull(sample);
        Assert.True(AllocationFailures.Count == 0, string.Join("; ", AllocationFailures));
    }
