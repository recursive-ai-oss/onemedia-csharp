    [Fact]
    public void OpusPacketDurations()
    {
        Assert.True(OpusToc.TryGetSamples([0x00], out int s));      // config 0: SILK NB 10 ms, one frame
        Assert.Equal(480, s);
        Assert.True(OpusToc.TryGetSamples([0xfc], out s));          // config 31: CELT FB 20 ms, one frame
        Assert.Equal(960, s);
        Assert.True(OpusToc.TryGetSamples([0xfd], out s));          // two frames
        Assert.Equal(1920, s);
        Assert.True(OpusToc.TryGetSamples([0xfb, 0x03], out s));    // code 3, three frames
