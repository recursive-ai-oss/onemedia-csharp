        Assert.False(OpusToc.TryGetSamples([], out _));
    }

    [Fact]
    public void AmrFraming()
    {
        Assert.True(AmrFrame.TryReadMagic("#!AMR\n"u8, out bool wb, out int len));
        Assert.False(wb);
        Assert.Equal(6, len);
        Assert.True(AmrFrame.TryReadMagic("#!AMR-WB\n"u8, out wb, out len));
        Assert.True(wb);
        Assert.Equal(9, len);
        Assert.False(AmrFrame.TryReadMagic("#!AMR_MC1.0\n"u8, out _, out _));

        int[] narrow = [13, 14, 16, 18, 20, 21, 27, 32, 6];
        for (int ft = 0; ft < narrow.Length; ft++)
        {
            Assert.True(AmrFrame.TryGetFrameSize((byte)(ft << 3 | 4), false, out int size));
            Assert.Equal(narrow[ft], size);
        }

        Assert.False(AmrFrame.TryGetFrameSize(10 << 3, false, out _));
        Assert.True(AmrFrame.TryGetFrameSize(15 << 3, false, out int none));
        Assert.Equal(1, none);
        Assert.True(AmrFrame.TryGetFrameSize(8 << 3, true, out int wide));
        Assert.Equal(61, wide);

        byte[] damr = new byte[AmrSpecificBox.Size];
        Assert.True(new AmrSpecificBox(0x4f4e4d44, 0, 0x81ff, 0, 1).TryWrite(damr));
        Assert.True(AmrSpecificBox.TryParse(damr, out AmrSpecificBox box));
        Assert.Equal(0x81ff, box.ModeSet);
    }

