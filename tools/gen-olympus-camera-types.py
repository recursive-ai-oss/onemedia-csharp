#!/usr/bin/env python3
"""Generate src/OneMedia/Metadata/OlympusCameraTypes.cs from the camera type values listed in ExifTool's Olympus tag documentation page.

Usage: gen-olympus-camera-types.py Olympus.html > OlympusCameraTypes.cs
The page is read as a table of facts (code -> model name); no program source is involved.
"""
import html
import re
import sys

text = open(sys.argv[1], encoding='utf8').read()
text = re.sub(r'<[^>]+>', '|', text)
text = html.unescape(text)
text = re.sub(r'\s*\|[\s|]*', '|', text)
entries = {}
for code, name in re.findall(r"'([A-Z0-9 ]{4,6})'\|= ([^|']+)", text):
    entries.setdefault(code.strip(), name.strip())
print('// Generated by tools/gen-olympus-camera-types.py from the camera type values in ExifTool\'s Olympus tag documentation; edit the script, not this file.')
print()
print('namespace RecursiveAI.OneMedia.Metadata;')
print()
print('/// <summary>The model names behind the camera type codes that Olympus cameras write in their movie headers.</summary>')
print('internal static class OlympusCameraTypes')
print('{')
print('    /// <summary>The model name for a camera type code (for example <c>D4586</c>), or null when the code is not listed.</summary>')
print('    public static string? Find(string code) => code switch')
print('    {')
for code in sorted(entries):
    print(f'        "{code}" => "{entries[code]}",')
print('        _ => null,')
print('    };')
print('}')
