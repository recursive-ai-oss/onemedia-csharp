#!/usr/bin/env python3
"""Pulls the fenced C# blocks out of the README and the migration pages into one file that samples/OneMedia.Snippets compiles.

A block is compiled as pasted: its leading `using Namespace;` lines become the file's usings, the rest becomes a method body, and the
project has the implicit usings of a new console app. A block that is only a fragment can be skipped by putting
`<!-- snippet-skip: reason -->` on the line before its fence; the reason is printed. Usage: extract.py <repo-root>
"""
import pathlib
import re
import shutil
import sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
files = [root / "README.md", *sorted((root / "docs" / "migration").glob("*.md"))]
ns_using = re.compile(r"^\s*using\s+[A-Za-z_][\w.]*\s*;\s*(//.*)?$")
count = skipped = 0
out = root / "samples" / "OneMedia.Snippets" / "obj" / "snippets"
shutil.rmtree(out, ignore_errors=True)
out.mkdir(parents=True)

for f in files:
    lines = f.read_text(encoding="utf-8").split("\n")
    i = 0
    while i < len(lines):
        if lines[i].strip() == "```csharp":
            skip = None
            j = i - 1
            while j >= 0 and not lines[j].strip():
                j -= 1
            m = re.match(r"<!--\s*snippet-skip:\s*(.*?)\s*-->", lines[j].strip()) if j >= 0 else None
            if m:
                skip = m.group(1)
            start = i + 1
            i += 1
            while lines[i].strip() != "```":
                i += 1
            block = lines[start:i]
            name = f"{f.relative_to(root)}:{start}"
            if skip is not None:
                skipped += 1
                print(f"skipped {name}: {skip}")
            else:
                usings: list[str] = []
                body = []
                for l in block:
                    if not body and ns_using.match(l):
                        usings.append(l.strip().split("//")[0].strip())
                    else:
                        body.append(l)
                count += 1
                # One file per block, so a block only sees the usings it shows (plus the implicit ones of a new console app).
                text = (f"// Generated by tools/snippets/extract.py from {name}.\n" + "\n".join(usings)
                        + f"\n\nnamespace Snippets;\n\ninternal static class Snippet{count}\n{{\n    private static async Task Run()\n    {{\n        await Task.CompletedTask;\n"
                        + "\n".join("        " + l for l in body) + "\n    }\n}\n")
                (out / f"Snippet{count}.cs").write_text(text, encoding="utf-8")
        i += 1

print(f"{count} snippets extracted, {skipped} skipped")
